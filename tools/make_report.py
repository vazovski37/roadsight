"""Collect every result into markdown tables + figures (results/summary.md, results/figures/*.png).

Sources: runs/*/metrics.json (training runs, PyTorch eval on GPU), results/*.json (extra evals),
results/onnx/*.json (ONNX variants on CPU), results/latency.json (CPU benchmark), results/fusion_*.json.

    python tools/make_report.py
"""
import json
import statistics
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

COLS = [("PQ", "PQ"), ("PQ_th", "PQ_th"), ("PQ_st", "PQ_st"), ("mAP", "mAP"), ("AP_S", "AP_S"),
        ("AP_thin", "AP thin"), ("mIoU", "mIoU"), ("IoU/traffic light", "IoU light"),
        ("IoU/traffic sign", "IoU sign"), ("IoU/pole", "IoU pole")]


def fmt(v, nd=1):
    return "–" if v is None else f"{v:.{nd}f}"


def row(name, m, extra=()):
    return "| " + " | ".join([name] + [fmt(m.get(k)) for k, _ in COLS] + list(extra)) + " |"


def header(extra=()):
    names = ["run"] + [c for _, c in COLS] + list(extra)
    return "| " + " | ".join(names) + " |\n|" + "---|" * len(names)


def load_runs():
    runs = {}
    for p in sorted(Path("runs").glob("*/metrics.json")):
        m = json.loads(p.read_text())
        runs[p.parent.name] = {"val": {k[4:]: v for k, v in m.items() if k.startswith("val/")},
                               "holdout": {k[8:]: v for k, v in m.items() if k.startswith("holdout/")},
                               "params_M": m.get("params_M")}
    return runs


def main():
    out = Path("results")
    figs = out / "figures"
    figs.mkdir(parents=True, exist_ok=True)
    runs = load_runs()
    extra = {p.stem: json.loads(p.read_text()) for p in out.glob("*.json")}
    lines = ["# RoadSight results (generated by tools/make_report.py)", ""]

    lines += ["## Training runs (val, PyTorch on GPU, default fusion settings)", "", header(["params M"])]
    for name, r in runs.items():
        lines.append(row(name, r["val"], [fmt(r["params_M"], 2)]))

    seeds = [runs[n]["val"] for n in ("r18_640", "r18_640_s1", "r18_640_s2") if n in runs]
    if len(seeds) >= 2:
        lines += ["", "## Noise floor: r18_640 with 3 seeds (mean ± std)", "",
                  "| metric | mean | std | min | max |", "|---|---|---|---|---|"]
        for k, c in COLS:
            vals = [s[k] for s in seeds if k in s]
            if len(vals) >= 2:
                lines.append(f"| {c} | {statistics.mean(vals):.2f} | {statistics.stdev(vals):.2f} | "
                             f"{min(vals):.2f} | {max(vals):.2f} |")

    tt = {k: v for k, v in extra.items() if k.startswith("tt_") or k.startswith("e1_")}
    if tt:
        lines += ["", "## Extra evaluations (val)", "", header(["size"])]
        for name, m in sorted(tt.items()):
            lines.append(row(name, m, [str(m.get("size"))]))

    onnx = {p.stem.replace("_val", ""): json.loads(p.read_text()) for p in (out / "onnx").glob("*_val.json")}
    lat = {}
    if (out / "latency.json").exists():
        L = json.loads((out / "latency.json").read_text())
        lat = {m["name"]: m for m in L["models"]}
        lines += ["", "## CPU deployment ladder (val accuracy on CPU + latency)", "",
                  f"Machine: {L['machine'].get('cpu')}, {L['protocol']['threads']} threads pinned to "
                  f"CPUs {L['protocol']['cpus']}, {L['protocol']['frames']} frames after {L['protocol']['warmup']} "
                  "warm-up, median (p90) end-to-end ms.", "",
                  header(["MB", "zip MB", "model ms", "total ms (p90)"])]
        for name, m in lat.items():
            acc = onnx.get(name, {})
            lines.append(row(name, acc, [fmt(m["file_mb"]), fmt(m.get("zipped_mb")), fmt(m["model_median_ms"]),
                                         f"{m['total_median_ms']:.1f} ({m['total_p90_ms']:.1f})"]))

        # Pareto figure: PQ vs latency
        pts = [(m["total_median_ms"], onnx[n]["PQ"], n) for n, m in lat.items() if n in onnx and "PQ" in onnx[n]]
        if pts:
            fig, ax = plt.subplots(figsize=(8, 5.5))
            for ms, pq, n in pts:
                ax.scatter(ms, pq, s=30)
                ax.annotate(n, (ms, pq), fontsize=7, xytext=(4, 2), textcoords="offset points")
            front, best = [], -1
            for ms, pq, n in sorted(pts):
                if pq > best:
                    front.append((ms, pq))
                    best = pq
            ax.plot(*zip(*front), "--", lw=1, color="gray", label="Pareto front")
            ax.axvline(100, color="red", lw=1, ls=":", label="100 ms budget")
            ax.set_xscale("log")
            ax.set_xlabel("end-to-end latency, median ms (4 P-cores, log scale)")
            ax.set_ylabel("PQ (val)")
            ax.set_title("Speed / accuracy of every deployed variant")
            ax.legend()
            fig.tight_layout()
            fig.savefig(figs / "pareto_pq_latency.png", dpi=140)

            fig, ax = plt.subplots(figsize=(8, 5.5))
            for key, label in (("IoU/traffic light", "traffic light IoU"), ("IoU/traffic sign", "traffic sign IoU"),
                               ("IoU/pole", "pole IoU"), ("AP_S", "AP small"), ("mIoU", "mIoU (all)")):
                xs = sorted((lat[n]["total_median_ms"], onnx[n].get(key)) for n in lat if n in onnx and key in onnx[n])
                ax.plot([x for x, _ in xs], [y for _, y in xs], "o-", ms=3, label=label)
            ax.set_xscale("log")
            ax.set_xlabel("end-to-end latency, median ms (log scale)")
            ax.set_ylabel("score")
            ax.set_title("Thin / small classes vs latency")
            ax.legend()
            fig.tight_layout()
            fig.savefig(figs / "thin_classes_latency.png", dpi=140)

    for p in sorted(out.glob("fusion_*.json")):
        f = json.loads(p.read_text())
        lines += ["", f"## Fusion tuning ({p.stem})", "", f"best on holdout: `{f['best']}`", "",
                  "| setting | PQ | PQ_th | PQ_st |", "|---|---|---|---|"]
        for k in ("val_default", "val_tuned", "val_tuned_without_thin_exemption"):
            m = f[k]
            lines.append(f"| {k} | {m['PQ']:.2f} | {m['PQ_th']:.2f} | {m['PQ_st']:.2f} |")

    # training curves
    fig, ax = plt.subplots(figsize=(8, 5))
    for name in ("teacher_r50", "r18_640", "r18_lite", "mbv3_lite", "r18_lite_kd"):
        p = Path("runs", name, "train_log.csv")
        if p.exists():
            import csv
            rows = list(csv.DictReader(open(p)))
            ax.plot([int(r["iter"]) for r in rows], [float(r["loss"]) for r in rows], lw=1, label=name)
    ax.set_xlabel("iteration")
    ax.set_ylabel("training loss")
    ax.set_ylim(0, 4)
    ax.legend()
    fig.tight_layout()
    fig.savefig(figs / "training_loss.png", dpi=140)

    (out / "summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
